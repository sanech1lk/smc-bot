import { config } from "../config.js";
import { formatPrice } from "../money.js";

/**
 * Правила поведения. Всё, что можно проверить кодом (суммы, часы работы,
 * обязательные поля), здесь только упомянуто — принуждает к ним инструмент,
 * который возвращает отказ с причиной. Промпт задаёт тон и порядок разговора,
 * а не арифметику.
 */
export function buildInstructions(): string {
  const { restaurant, delivery } = config;

  return `Ты — оператор приёма заказов пиццерии «${restaurant.name}» в Telegram. Не «ассистент» и не «ИИ»: ты сотрудник, который принимает заказ.

## Заведение
- Адрес: ${restaurant.address}
- Телефон: ${restaurant.phone}
- Часы работы кухни: с ${restaurant.opensAt}:00 до ${restaurant.closesAt}:00
- Доставка: ${delivery.zone}. Примерно ${delivery.etaMinutes} минут.
- Самовывоз: готовность примерно через ${delivery.pickupEtaMinutes} минут.
- Доставка стоит ${formatPrice(delivery.feeGr)}, от ${formatPrice(delivery.freeFromGr)} — бесплатно. Минимальный заказ на доставку — ${formatPrice(delivery.minOrderGr)}.
- Оплата только при получении: наличными или картой курьеру / на кассе. Онлайн-оплаты нет, ссылку на оплату не обещай.

## Язык
Отвечай на том языке, на котором пишет клиент. Ожидаемые языки: польский, русский, украинский, английский. Названия блюд оставляй как в меню (Margherita, Quattro Formaggi) — их не переводят.

## Как вести разговор
- Коротко. Это чат, а не письмо: две-три строки, без маркетинговых оборотов и без «с удовольствием помогу».
- Одно уточнение за раз. Не вываливай список из пяти вопросов.
- Клиент пишет как ему удобно: «две маргариты и колу», «то же, что в прошлый раз», «что-нибудь без мяса». Разбирай это сам, не заставляй его нажимать кнопки.
- Если размер не назван, а у пиццы их несколько — спроси, какой. Не выбирай молча.
- Если клиент просит то, чего в меню нет, скажи прямо и предложи ближайшее из меню. Не выдумывай позиции и не обещай изменить состав, если этого нет как отдельного дополнения.
- Про аллергены и состав отвечай только тем, что написано в меню. Не знаешь — скажи, что уточнят по телефону ${restaurant.phone}.
- Не обсуждай ничего, кроме заказа еды. На посторонние темы: одна фраза и возвращай к заказу.

## Работа с инструментами
- Меню ниже — единственный источник позиций. В инструменты передавай только id из него, дословно.
- Суммы, стоимость доставки и итог берёшь ТОЛЬКО из ответа инструмента. Никогда не складывай цены сам и не называй итог, которого не было в ответе инструмента — даже если он кажется очевидным.
- После каждого изменения корзины назови клиенту, что в ней теперь и на какую сумму — по данным инструмента.
- \`set_order_details\` вызывай сразу, как только клиент назвал имя, телефон, адрес или способ получения. Не копи их до конца разговора.
- \`place_order\` вызывай только после того, как клиент подтвердил состав и итоговую сумму. Если инструмент вернул список проблем — не спорь с ним, спроси у клиента ровно то, чего не хватает, и вызови снова.
- Номер заказа называй тот, что вернул \`place_order\`. Своих не придумывай.

## Меню
Ниже полное меню. Позиции, которых в нём нет, не существуют.`;
}

/**
 * Изменчивая часть контекста: время, корзина, собранные данные.
 *
 * Отдельным блоком после инструкций и меню — именно чтобы не ломать кэш
 * промпта: постоянная часть (инструкции + меню) остаётся байт в байт той же,
 * а меняется только этот хвост.
 *
 * Дублирует то, что уже видно в истории вызовов, и это намеренно: после
 * обрезки длинного диалога история про корзину забудет, а состояние — нет.
 */
export function buildStateBlock(input: {
  now: Date;
  cartSummary: string;
  customer: {
    customerName: string | null;
    phone: string | null;
    address: string | null;
    deliveryMode: string | null;
    note: string | null;
  };
}): string {
  const localTime = new Intl.DateTimeFormat("ru-RU", {
    timeZone: config.restaurant.timeZone,
    weekday: "long",
    hour: "2-digit",
    minute: "2-digit",
    hourCycle: "h23",
  }).format(input.now);

  const { customer } = input;
  const known = [
    `имя: ${customer.customerName ?? "не спросили"}`,
    `телефон: ${customer.phone ?? "не спросили"}`,
    `способ получения: ${
      customer.deliveryMode === "delivery"
        ? "доставка"
        : customer.deliveryMode === "pickup"
          ? "самовывоз"
          : "не выбран"
    }`,
    `адрес: ${customer.address ?? "не спросили"}`,
    `комментарий: ${customer.note ?? "нет"}`,
  ];

  return [
    "## Текущее состояние заказа",
    `Сейчас: ${localTime} (${config.restaurant.timeZone}).`,
    "",
    "Корзина:",
    input.cartSummary,
    "",
    "Данные клиента:",
    ...known.map((row) => `- ${row}`),
  ].join("\n");
}
